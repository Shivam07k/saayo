// A shopper has no admin permissions at all, so "has any" is the admin test.
export function isAdmin(user) {
  if (!user) return false;
  if (user.roleName === ROLES.SUPER_ADMIN) return true;
  return (user.permissions || []).some((p) => Object.values(PERMISSIONS).includes(p));
}